// Pulls the design from the extension (the single source of truth) into the site.
// Runs before `dev` and `build`; everything it writes is git-ignored.
//   content/styles.js  -> generated/fox-shared.css  (tokens, mascot sprite rules, keyframes)
//   content/icons.js   -> generated/icons.json      (the same pixel icons as the panel)
//   manifest.json      -> generated/meta.json       (name, version, shortcut)
//   assets/, icons/    -> public/assets/, public/icons/
import { readFileSync, writeFileSync, mkdirSync, cpSync, existsSync } from "node:fs";
import vm from "node:vm";

const ext = new URL("../../", import.meta.url);
const read = (p) => readFileSync(new URL(p, ext), "utf8");
const out = new URL("../generated/", import.meta.url);
mkdirSync(out, { recursive: true });

// --- CSS: take the stylesheet text out of getFoxStyles() ---
const styles = read("content/styles.js");
let css = styles.slice(styles.indexOf("return `") + 8, styles.lastIndexOf("`;"));
// chrome.runtime.getURL(...) paths -> the same paths under public/
css = css.replace(/\$\{asset\('([^']+)'\)\}/g, 'url("/$1")');
if (css.includes("${")) throw new Error("styles.js has an interpolation sync-design.mjs doesn't know");

const block = (start) => {
  const i = css.indexOf(start);
  if (i < 0) throw new Error(`styles.js: "${start}" not found`);
  let depth = 0;
  for (let j = css.indexOf("{", i); j < css.length; j++) {
    if (css[j] === "{") depth++;
    else if (css[j] === "}" && --depth === 0) return css.slice(i, j + 1);
  }
};
const section = (title) => {
  const i = css.indexOf(title);
  const end = css.indexOf("/* ====", css.indexOf("*/", css.indexOf("*/", i) + 2) + 2);
  if (i < 0 || end < 0) throw new Error(`styles.js: section "${title}" not found`);
  return css.slice(css.lastIndexOf("/*", i), end);
};
const keyframes = css.match(/@keyframes fox-(frames-\d|blink-frame) .*$/gm);

writeFileSync(
  new URL("fox-shared.css", out),
  [
    "/* Generated by scripts/sync-design.mjs from content/styles.js. Do not edit. */",
    block(":host {").replace(":host", ":root"),
    section("Mascot sprite"),
    ...keyframes,
  ].join("\n") + "\n",
);

// --- Icons ---
const ctx = vm.createContext({ SafeHtml: class {} });
vm.runInContext(read("content/icons.js"), ctx);
writeFileSync(new URL("icons.json", out), JSON.stringify(vm.runInContext("ICONS", ctx), null, 1));

// --- Manifest facts ---
const manifest = JSON.parse(read("manifest.json"));
writeFileSync(
  new URL("meta.json", out),
  JSON.stringify({
    name: manifest.name,
    version: manifest.version,
    description: manifest.description,
    shortcut: manifest.commands?._execute_action?.suggested_key?.default ?? "",
  }, null, 1),
);

// --- Binary assets ---
const pub = new URL("../public/", import.meta.url);
for (const dir of ["assets/sprites", "assets/fonts", "assets/store", "assets/web", "icons"]) {
  if (!existsSync(new URL(dir, ext))) continue;
  // icons/ also holds the big source art (original*.png): only the built sizes ship
  cpSync(new URL(dir, ext), new URL(dir, pub), { recursive: true, filter: (src) => !/original/.test(src) });
}

console.log(`sync-design: v${manifest.version}, ${Object.keys(vm.runInContext("ICONS", ctx)).length} icons, ${keyframes.length} keyframes`);
